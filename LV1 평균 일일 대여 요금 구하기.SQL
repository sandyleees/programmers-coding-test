-- -- CAR_RENTAL_COMPANY_CAR 테이블에서 자동차 종류가 'SUV'인 자동차들의 
-- 평균 일일 대여 요금을 출력하는 SQL문을 작성해주세요.
-- --  이때 평균 일일 대여 요금은 소수 첫 번째 자리에서 반올림하고,
--  컬럼명은 AVERAGE_FEE 로 지정해주세요.

SELECT ROUND(AVG(DAILY_FEE),0) AS AVERAGE_FEE
FROM CAR_RENTAL_COMPANY_CAR
WHERE CAR_TYPE = 'SUV'


-- # SUV 종류의 (종류별) -> 평균 일일 대여 요금 소수 첫번째 반올림, 별칭지정
-- # SUV라는 그룹의 평균 요금 --- GROUP BY
